-- Сверка при операциях с неясным исходом (находка М-6, шаг 1.5 плана, 13 ноября 2026).
--
-- Раньше, пока по кошельку висела хоть одна операция `unknown`, сверка его пропускала, и
-- недостача не ловилась, пока заявку не разберёт человек. Теперь сверка считает оба варианта
-- каждой такой операции — «выполнена» и «не выполнена» — и сравнивает реальный баланс со всеми
-- сочетаниями (`domain::reconcile`). Сходится с одним — порядок и подсказка оператору, какие
-- операции, судя по балансу, выполнились; ни с одним — тревога как при расхождении.
-- `expected` по-прежнему — баланс по леджеру.

ALTER TABLE reconciliations
    -- Операции `unknown` по кошельку на момент замера.
    ADD COLUMN unsettled_ops BIGINT[] NOT NULL DEFAULT '{}',
    -- Те из них, что, судя по балансу, выполнились; пусто — ни одна. NULL — подсказки нет:
    -- баланс не сходится ни с одним сочетанием или сходится сразу с несколькими.
    ADD COLUMN matched_ops BIGINT[];

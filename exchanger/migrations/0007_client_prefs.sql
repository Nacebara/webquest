-- Выбор клиента, который переживает перезапуск бота (шаг 6.3 плана, находка К-4): «Простой вид»
-- вместо карточек и «Поддержка» нажата — следующий текст клиента уходит оператору. Раньше это
-- жило только в памяти бота и пропадало при перезапуске: вопрос клиента получал подсказку
-- «Пришлите чек…», а карточки снова шли красивым видом.
CREATE TABLE client_prefs (
    user_id         BIGINT PRIMARY KEY,
    plain_view      BOOLEAN NOT NULL DEFAULT FALSE,
    -- «Поддержка» нажата: с какой заявкой (может не быть) и когда. NULL — вопроса не ждём.
    support_order   TEXT,
    support_since   TIMESTAMPTZ,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- «Деньги пришли» не больше того, что реально лежит в кошельке (находка М-5, шаг 1.6 плана,
-- 13 ноября 2026).
--
-- Ручное подтверждение прихода движок ограничивает излишком кошелька по последнему замеру:
-- реальный баланс минус баланс по леджеру. Пока по кошельку висит активация с неясным исходом,
-- сумма которой неизвестна, сверка не может вынести вердикт (`skipped_inflight`), но баланс
-- прочитать может — и как раз этот замер нужен человеку. Раньше у пропущенной сверки в `actual`
-- стоял баланс по леджеру (замера не было), и отличить настоящий замер от пропуска было нельзя.

ALTER TABLE reconciliations
    -- Баланс прочитан у кошелька, и пока читали, ни одна операция не началась и не решилась:
    -- `actual` — настоящий замер. FALSE — замера не было, `actual` = `expected`.
    ADD COLUMN balance_read BOOLEAN NOT NULL DEFAULT TRUE;

-- Прежние пропуски замером не считаем: баланс в них или не читался, или читался во время гонки.
UPDATE reconciliations SET balance_read = FALSE WHERE verdict = 'skipped_inflight';

-- Критичные тревоги: «Принял» гасит, повтор раз в 15 минут, копии переживают перезапуск (шаг 2.8
-- плана, находки Ю-3 и AUDIT-UI П1; выбор владельца 14 ноября 2026 — повтор новым сообщением со
-- звуком, прежнее удаляется).
--
-- Тревога-состояние (недостача, заявка на разборе, вход сброшен) поднимается заново на каждом
-- круге, пока причина не ушла. Раньше после «Принял» следующий круг открывал новую тревогу со
-- звуком. Теперь «Принял» гасит её до тех пор, пока причина не уйдёт (`resolved_at`) и не
-- появится снова. Тревоги-события (новое обращение клиента) — как раньше.

ALTER TABLE alerts
    -- Причина ушла сама (не человек): следующий подъём с этим ключом — новая тревога.
    ADD COLUMN resolved_at TIMESTAMPTZ,
    -- Сколько раз критичная тревога повторена новым сообщением, пока её никто не принял.
    ADD COLUMN repeats INTEGER NOT NULL DEFAULT 0;

-- Прежние закрытые тревоги закрыты и по причине: новый подъём откроет новую.
UPDATE alerts SET resolved_at = acked_at WHERE acked_at IS NOT NULL;

-- Копии тревоги у каждого сотрудника: правка при повторе события, удаление прежней при повторе
-- критичной, правка у всех после «Принял». Раньше это хранилось только в памяти пульта.
CREATE TABLE alert_copies (
    alert_id            BIGINT NOT NULL REFERENCES alerts(id),
    chat_id             BIGINT NOT NULL,
    message_id          INTEGER NOT NULL,
    sent_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (alert_id, chat_id)
);
